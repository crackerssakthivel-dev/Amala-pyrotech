-- Secure public checkout RPCs: browser never needs SELECT access to customer/order tables.
create or replace function public.create_checkout_order(p_payload jsonb)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer_id bigint;
  v_order_pk bigint;
  v_order_id text := p_payload->>'order_id';
  v_item jsonb;
begin
  insert into customers(name,mobile,district,state,town,address,pincode,updated_at)
  values(
    coalesce(p_payload->>'name',''), regexp_replace(coalesce(p_payload->>'mobile',''),'\D','','g'),
    p_payload->>'district', p_payload->>'state', p_payload->>'town', p_payload->>'address', p_payload->>'pincode', now()
  )
  on conflict(mobile) do update set
    name=excluded.name, district=excluded.district, state=excluded.state,
    town=excluded.town, address=excluded.address, pincode=excluded.pincode, updated_at=now()
  returning id into v_customer_id;

  insert into orders(order_id,customer_id,customer_name,mobile,pincode,state,district,town,address,status,total_mrp,savings,net_total,coupon_discount,packing_charges,grand_total,transport,invoice_snapshot)
  values(v_order_id,v_customer_id,p_payload->>'name',regexp_replace(coalesce(p_payload->>'mobile',''),'\D','','g'),p_payload->>'pincode',p_payload->>'state',p_payload->>'district',p_payload->>'town',p_payload->>'address','pending',
    (p_payload->>'total_mrp')::numeric,(p_payload->>'savings')::numeric,(p_payload->>'net_total')::numeric,(p_payload->>'coupon_discount')::numeric,(p_payload->>'packing_charges')::numeric,(p_payload->>'grand_total')::numeric,coalesce(p_payload->>'transport','To-Pay at Lorry Hub'),p_payload->'invoice_snapshot')
  returning id into v_order_pk;

  for v_item in select * from jsonb_array_elements(p_payload->'items') loop
    insert into order_items(order_id,product_id,code,name,pack,mrp,price,qty,amount)
    values(v_order_pk,(v_item->>'product_id')::bigint,v_item->>'code',v_item->>'name',v_item->>'pack',(v_item->>'mrp')::numeric,(v_item->>'price')::numeric,(v_item->>'qty')::integer,(v_item->>'amount')::numeric);
  end loop;
  return v_order_id;
end;
$$;
grant execute on function public.create_checkout_order(jsonb) to anon, authenticated;

create or replace function public.track_order(p_value text)
returns table(order_id text, status text, created_at timestamptz, customer_name text)
language sql
security definer
set search_path=public
as $$
  select o.order_id,o.status,o.created_at,o.customer_name from orders o
  where lower(o.order_id)=lower(trim(p_value)) or o.mobile=regexp_replace(trim(p_value),'\D','','g')
  order by o.created_at desc limit 1;
$$;
grant execute on function public.track_order(text) to anon, authenticated;

