  id bigint generated by default as identity primary key,
  name text not null,
  mobile text not null unique,
  district text,
  state text,
  town text,
  address text,
  pincode text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists orders (
  id bigint generated by default as identity primary key,
  order_id text not null unique,
  customer_id bigint references customers(id) on delete set null,
  customer_name text not null,
  mobile text not null,
  pincode text,
  state text,
  district text,
  town text,
  address text,
  status text not null default 'pending' check(status in ('pending','confirmed','cancelled')),
  total_mrp numeric(12,2) not null default 0,
  savings numeric(12,2) not null default 0,
  net_total numeric(12,2) not null default 0,
  coupon_discount numeric(12,2) not null default 0,
  packing_charges numeric(12,2) not null default 0,
  grand_total numeric(12,2) not null default 0,
  transport text default 'To-Pay at Lorry Hub',
  invoice_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  confirmed_at timestamptz,
  cancelled_at timestamptz
);
create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  product_id bigint references products(id) on delete set null,
  code text not null,
  name text not null,
  pack text,
  mrp numeric(12,2) not null default 0,
  price numeric(12,2) not null default 0,
  qty integer not null check(qty > 0),
  amount numeric(12,2) not null default 0
);

create index if not exists orders_status_idx on orders(status);
create index if not exists orders_mobile_idx on orders(mobile);
create index if not exists orders_district_idx on orders(district);

